-- 1. Asegurar extensión pgcrypto para generación de UUIDs y hashes seguros
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 2. Asegurar estructura de PERSONA con password_hash y pin_hash (HU-SEG-06)
CREATE TABLE IF NOT EXISTS persona (
    id_persona BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(15) UNIQUE NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL DEFAULT '',
    telefono VARCHAR(20) NOT NULL,
    direccion VARCHAR(255),
    password_hash VARCHAR(255) NOT NULL, -- Hash bcrypt (cost factor 10-12)
    pin_hash VARCHAR(255) NOT NULL,      -- Hash bcrypt para PIN secreto de 4 dígitos
    rol VARCHAR(20) NOT NULL DEFAULT 'ciudadano', -- HU-SEG-05 (ciudadano / administrador)
    intentos_fallidos INT NOT NULL DEFAULT 0,    -- HU-SEG-03 (control de fuerza bruta)
    bloqueado_hasta TIMESTAMPTZ,                 -- HU-SEG-03 (bloqueo temporal 15 min)
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla CODIGO_OTP (HU-SEG-01: Verificación OTP de 6 dígitos por WhatsApp)
CREATE TABLE IF NOT EXISTS codigo_otp (
    id_otp BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(15) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    codigo VARCHAR(6) NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL, -- Validez de 5 minutos
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    intentos INT NOT NULL DEFAULT 0, -- Intentos fallidos de verificación (anti fuerza bruta)
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_otp_dni_tel ON codigo_otp(dni, telefono, expira_en);

-- 4. Tabla SESION_USUARIO (HU-SEG-02: Sesión persistente con token único revocable)
CREATE TABLE IF NOT EXISTS sesion_usuario (
    id_sesion UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_persona BIGINT REFERENCES persona(id_persona) ON DELETE CASCADE,
    dni VARCHAR(15) NOT NULL,
    token_jwt TEXT NOT NULL,
    dispositivo_info VARCHAR(255),
    revocado BOOLEAN NOT NULL DEFAULT FALSE, -- Revocable ante reporte de robo
    expira_en TIMESTAMPTZ NOT NULL,          -- 30 a 90 días de duración
    created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_sesion_dni ON sesion_usuario(dni, revocado, expira_en);

