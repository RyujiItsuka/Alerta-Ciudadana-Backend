-- ==============================================================================
-- ALERTA CIUDADANA - MIGRACIÓN DE SEGURIDAD MILITAR
-- 1. Tabla Aislada de Soporte / Desarrolladores (cuenta_soporte)
-- 2. Encriptación Criptográfica con bcrypt (pgcrypto)
-- 3. Funciones RPC de Autenticación y Creación Segura sin Exponer Contraseñas
-- ==============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. TABLA EXCLUSIVA PARA SUPERADMIN (SOPORTE TÉCNICO & DESARROLLADORES)
-- Aislamiento total de personal municipal y ciudadanos
CREATE TABLE IF NOT EXISTS cuenta_soporte (
    id_soporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) UNIQUE NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) DEFAULT 'superadmin' CHECK (rol = 'superadmin'),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    ultimo_acceso TIMESTAMPTZ
);

-- Insertar Superadmin Maestro (Desarrollador).
-- ⚠️ SEGURIDAD: sin contraseñas hardcodeadas. Reemplace el marcador por una
--    contraseña fuerte propia antes de ejecutar; el bloque aborta si no se
--    reemplazó (así el repositorio nunca contiene credenciales funcionales).
DO $$
DECLARE
    v_password text := 'CAMBIAR_ESTA_CLAVE_ANTES_DE_EJECUTAR';
BEGIN
    IF v_password = 'CAMBIAR_ESTA_CLAVE_ANTES_DE_EJECUTAR' THEN
        RAISE EXCEPTION 'Edite cuenta_soporte_y_encriptacion.sql y reemplace la contraseña de soporte antes de ejecutarlo.';
    END IF;

    INSERT INTO cuenta_soporte (usuario, nombres, apellidos, email, password_hash, rol)
    VALUES (
        'soporte',
        'Soporte Técnico',
        'Alerta Ciudadana Dev',
        'soporte@alertaciudadana.pe',
        crypt(v_password, gen_salt('bf', 10)),
        'superadmin'
    )
    ON CONFLICT (usuario) DO UPDATE
    SET password_hash = EXCLUDED.password_hash,
        rol = 'superadmin';
END $$;

-- 2. ENCRIPTACIÓN DE CONTRASEÑAS EN operador_central (ADMINISTRADORES Y TÉCNICOS)
-- Cifrar cualquier contraseña previa existente que aún esté en texto plano,
-- conservando la misma clave (se re-hashea el valor existente con bcrypt).
-- NO se fuerza ninguna contraseña conocida.
UPDATE operador_central
SET password_hash = crypt(password_hash, gen_salt('bf', 10))
WHERE password_hash NOT LIKE '$2a$%';

-- 3. FUNCIÓN RPC SEGURA DE LOGIN (Valida internamente en el servidor sin retornar contraseñas)
CREATE OR REPLACE FUNCTION login_personal(p_usuario text, p_password text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_soporte cuenta_soporte%ROWTYPE;
    v_operador operador_central%ROWTYPE;
BEGIN
    -- Fase A: Verificar si es Superadmin en cuenta_soporte
    SELECT * INTO v_soporte
    FROM cuenta_soporte
    WHERE LOWER(usuario) = LOWER(TRIM(p_usuario));

    IF FOUND THEN
        IF v_soporte.password_hash LIKE '$2%'
           AND v_soporte.password_hash = crypt(p_password, v_soporte.password_hash) THEN
            
            UPDATE cuenta_soporte 
            SET ultimo_acceso = NOW() 
            WHERE id_soporte = v_soporte.id_soporte;

            RETURN jsonb_build_object(
                'success', true,
                'id', 'SA-' || v_soporte.id_soporte,
                'usuario', v_soporte.usuario,
                'nombre', v_soporte.nombres || ' ' || v_soporte.apellidos,
                'rol', 'superadmin',
                'cargo', 'Soporte Técnico & Desarrollador'
            );
        ELSE
            RETURN jsonb_build_object('success', false, 'error', 'Contraseña de soporte incorrecta');
        END IF;
    END IF;

    -- Fase B: Verificar si es Administrador o Técnico en operador_central
    SELECT * INTO v_operador
    FROM operador_central
    WHERE LOWER(usuario) = LOWER(TRIM(p_usuario));

    IF FOUND THEN
        IF v_operador.estado = 'suspendido' OR v_operador.estado = 'inactivo' THEN
            RETURN jsonb_build_object('success', false, 'error', 'Tu cuenta se encuentra suspendida o inactiva');
        END IF;

        IF v_operador.password_hash LIKE '$2%'
           AND v_operador.password_hash = crypt(p_password, v_operador.password_hash) THEN

            UPDATE operador_central SET ultimo_acceso = NOW() WHERE id_operador = v_operador.id_operador;

            RETURN jsonb_build_object(
                'success', true,
                'id', 'OP-' || v_operador.id_operador,
                'usuario', v_operador.usuario,
                'nombre', v_operador.nombres || ' ' || v_operador.apellidos,
                'rol', v_operador.rol,
                'cargo', CASE WHEN v_operador.rol = 'administrador' THEN 'Administrador General de Central' ELSE 'Técnico de Central de Alertas' END,
                'turno', v_operador.turno
            );
        ELSE
            RETURN jsonb_build_object('success', false, 'error', 'Contraseña incorrecta');
        END IF;
    END IF;

    RETURN jsonb_build_object('success', false, 'error', 'Usuario no registrado en el sistema');
END;
$$;

-- 4. FUNCIÓN RPC PARA CREAR ADMINISTRADORES O TÉCNICOS CON CONTRASEÑA ENCRIPTADA
CREATE OR REPLACE FUNCTION crear_operador_seguro(
    p_usuario text,
    p_nombres text,
    p_apellidos text,
    p_dni text,
    p_telefono text,
    p_password text,
    p_rol text,
    p_turno text DEFAULT 'Mañana'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_new_id bigint;
BEGIN
    INSERT INTO operador_central (
        usuario,
        nombres,
        apellidos,
        dni,
        telefono,
        password_hash,
        rol,
        turno,
        estado
    ) VALUES (
        TRIM(p_usuario),
        TRIM(p_nombres),
        TRIM(p_apellidos),
        p_dni,
        p_telefono,
        crypt(p_password, gen_salt('bf', 10)),
        p_rol,
        p_turno,
        'activo'
    )
    RETURNING id_operador INTO v_new_id;

    RETURN jsonb_build_object('success', true, 'id_operador', v_new_id);
EXCEPTION WHEN unique_violation THEN
    RETURN jsonb_build_object('success', false, 'error', 'El nombre de usuario ya existe');
END;
$$;

-- 5. SEGURIDAD DE FILAS (ROW LEVEL SECURITY)
ALTER TABLE cuenta_soporte ENABLE ROW LEVEL SECURITY;
ALTER TABLE operador_central ENABLE ROW LEVEL SECURITY;

-- cuenta_soporte: ningún acceso directo anónimo
DROP POLICY IF EXISTS "Denegar acceso directo a cuenta_soporte" ON cuenta_soporte;
CREATE POLICY "Denegar acceso directo a cuenta_soporte" ON cuenta_soporte
    FOR ALL TO anon USING (false);

-- operador_central: CERRADA al navegador (rol anon). La app web gestiona estas
-- cuentas a través de la Edge Function `security` (staff-save / staff-delete /
-- list-operadores), que opera con la service_role dentro del servidor.
-- Se eliminan las políticas permisivas heredadas y NO se crea ninguna nueva:
-- con RLS activo y sin políticas, únicamente service_role puede leer o escribir.
DROP POLICY IF EXISTS "Permitir lectura operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir insercion operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir modificacion operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir eliminacion operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir lectura en operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir insercion en operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir actualizacion en operador_central" ON operador_central;
DROP POLICY IF EXISTS "Permitir eliminacion en operador_central" ON operador_central;
DROP POLICY IF EXISTS "operador_central_block_all_anon" ON operador_central;

