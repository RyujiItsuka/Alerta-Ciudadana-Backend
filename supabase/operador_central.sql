-- ==============================================================================
-- ALERTA CIUDADANA - TABLA EXCLUSIVA DE PERSONAL DE CENTRAL (OPERADORES Y ADMINS)
-- Arquitectura de Seguridad Institucional: Aislamiento total de Ciudadanos
-- ==============================================================================

CREATE TABLE IF NOT EXISTS operador_central (
    id_operador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) UNIQUE NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni VARCHAR(15),
    telefono VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('administrador', 'tecnico')),
    turno VARCHAR(30) DEFAULT 'Mañana',
    estado VARCHAR(20) DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo', 'suspendido')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    ultimo_acceso TIMESTAMPTZ
);

