-- ALERTA CIUDADANA - TABLA EXCLUSIVA DE PERSONAL DE CENTRAL (OPERADORES Y ADMINS)
-- Arquitectura de Seguridad Institucional: Aislamiento total de Ciudadanos
-- ==============================================================================

-- Necesario para crypt()/gen_salt() (bcrypt). Idempotente.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS operador_central (
    id_operador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) UNIQUE NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni VARCHAR(15),
    telefono VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('administrador', 'tecnico')),
    turno VARCHAR(30) DEFAULT 'Mañana',
    estado VARCHAR(20) DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo', 'suspendido')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    ultimo_acceso TIMESTAMPTZ
);

-- PARCHE DE COMPATIBILIDAD (idempotente): si "operador_central" ya existía de
-- una versión anterior, asegura las columnas que usa el INSERT de abajo para
-- que el script no falle con "column ... does not exist".
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS dni VARCHAR(15);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS telefono VARCHAR(20);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS nombres VARCHAR(100);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS apellidos VARCHAR(100);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS rol VARCHAR(20);
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS turno VARCHAR(30) DEFAULT 'Mañana';
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS estado VARCHAR(20) DEFAULT 'activo';
ALTER TABLE operador_central ADD COLUMN IF NOT EXISTS ultimo_acceso TIMESTAMPTZ;

-- Insertar Administrador Maestro.
-- ⚠️ SEGURIDAD: NO se hardcodea ninguna contraseña funcional. Reemplace el
--    marcador por una contraseña fuerte propia antes de ejecutar el script.
--    El bloque aborta si el marcador sigue presente, de modo que nunca quede
--    una credencial conocida versionada en el repositorio.
DO $$
DECLARE
    v_password text := 'CAMBIAR_ESTA_CLAVE_ANTES_DE_EJECUTAR';
BEGIN
    IF v_password = 'CAMBIAR_ESTA_CLAVE_ANTES_DE_EJECUTAR' THEN
        RAISE EXCEPTION 'Edite operador_central.sql y reemplace la contraseña del administrador antes de ejecutarlo.';
    END IF;

    INSERT INTO operador_central (usuario, nombres, apellidos, dni, telefono, password_hash, rol, estado)
    VALUES (
        'admin',
        'Administrador General',
        'Central Pisco',
        '00000001',
        '976264949',
        crypt(v_password, gen_salt('bf', 10)),
        'administrador',
        'activo'
    )
    ON CONFLICT (usuario) DO NOTHING;
END $$;

-- Índices de consulta rápida
CREATE INDEX IF NOT EXISTS idx_operador_usuario ON operador_central(usuario);
CREATE INDEX IF NOT EXISTS idx_operador_rol ON operador_central(rol);
